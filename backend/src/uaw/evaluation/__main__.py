"""Measure retrieval quality on a labeled question set.

Usage (from backend/, with VOYAGE_API_KEY set and the repository imported):
    uv run python -m uaw.evaluation eval/itsdangerous.json
    uv run python -m uaw.evaluation eval/itsdangerous.json --top-k 10 --json report.json
    uv run python -m uaw.evaluation eval/itsdangerous.json --split test

Each question costs one embedding API call. Nothing is generated by an LLM.
"""

import argparse
import asyncio
import sys
from pathlib import Path

from uaw.config import Settings
from uaw.embeddings.errors import EmbeddingError
from uaw.embeddings.voyage import VoyageEmbedder, VoyageReranker, create_voyage_http_client
from uaw.evaluation.dataset import EvalDataset, Split, load_dataset
from uaw.evaluation.runner import EvaluationError, EvaluationRun, evaluate_dataset, format_run
from uaw.retrieval.retriever import RetrievalOptions, Retriever
from uaw.storage.db import create_engine, create_session_factory
from uaw.storage.models import EMBEDDING_DIMENSIONS


async def run(
    dataset: EvalDataset,
    settings: Settings,
    top_k: int,
    split: Split | None = None,
    options: RetrievalOptions | None = None,
    rerank_model: str = "",
) -> EvaluationRun:
    if settings.voyage_api_key is None:
        raise EvaluationError("VOYAGE_API_KEY is not set (environment or backend/.env).")
    engine = create_engine(settings)
    try:
        async with create_voyage_http_client(settings.voyage_timeout_seconds) as http:
            embedder = VoyageEmbedder(
                http,
                api_key=settings.voyage_api_key.get_secret_value(),
                model=settings.embedding_model,
                dimensions=EMBEDDING_DIMENSIONS,
                max_retries=settings.voyage_max_retries,
            )
            reranker = None
            if rerank_model:
                reranker = VoyageReranker(
                    http,
                    api_key=settings.voyage_api_key.get_secret_value(),
                    model=rerank_model,
                    max_retries=settings.voyage_max_retries,
                )
            sessions = create_session_factory(engine)
            return await evaluate_dataset(
                dataset,
                Retriever(sessions, embedder, options, reranker),
                sessions,
                top_k=top_k,
                split=split,
            )
    finally:
        await engine.dispose()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m uaw.evaluation", description="Measure retrieval quality."
    )
    parser.add_argument("dataset", type=Path, help="labeled question set (JSON)")
    parser.add_argument("--top-k", type=int, default=10, help="chunks retrieved per question")
    parser.add_argument("--json", type=Path, help="also write the full report to this file")
    parser.add_argument(
        "--split",
        choices=["dev", "test"],
        help="only the questions of this split (default: all). Tune on dev, report on test.",
    )
    parser.add_argument(
        "--mode", choices=["vector", "hybrid"], default="vector", help="retrieval mode"
    )
    parser.add_argument(
        "--text-weight", type=float, default=1.0, help="weight of full text in hybrid mode"
    )
    parser.add_argument(
        "--text-terms",
        choices=["names", "words"],
        default="names",
        help="full text matches the question's code names, or every word",
    )
    parser.add_argument(
        "--test-weight",
        type=float,
        default=Settings.model_fields["retrieval_test_weight"].default,
        help="below 1, test files rank lower (default: the production setting)",
    )
    parser.add_argument(
        "--rerank-model",
        default=Settings.model_fields["rerank_model"].default,
        help="Voyage reranker, e.g. rerank-3 (default: the production setting)",
    )
    parser.add_argument(
        "--rerank-candidates",
        type=int,
        default=Settings.model_fields["rerank_candidates"].default,
        help="chunks given to the reranker",
    )
    args = parser.parse_args(argv)
    if not 1 <= args.top_k <= 50:
        parser.error("--top-k must be between 1 and 50")
    try:
        options = RetrievalOptions(
            mode=args.mode,
            text_weight=args.text_weight,
            text_terms=args.text_terms,
            test_weight=args.test_weight,
            rerank_candidates=args.rerank_candidates,
        )
    except ValueError as exc:
        parser.error(str(exc))

    dataset = load_dataset(args.dataset)
    try:
        result = asyncio.run(
            run(dataset, Settings(), args.top_k, args.split, options, args.rerank_model)
        )
    except (EvaluationError, EmbeddingError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1

    print(format_run(dataset, result))
    if args.json:
        args.json.write_text(result.model_dump_json(indent=2), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
